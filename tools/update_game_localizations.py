"""Join current API identities to installed game text IDs; never transliterate names.

First run tools/localization_gen/extract.lua with tests/run_lua.py --game ...
--work ... --isolated-profile. Inputs are explicit read-only snapshots. Output
contains only referenced texts, not the full localization dictionaries.
"""
import argparse
import copy
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = {'en': '03F97B57', 'zhs': '5942CCF7', 'zht': '9EBA952A'}
HASH_FIELDS = ('nameHash', 'descriptionGamePlayShortHash',
               'descriptionGamePlayLongHash', 'descriptionFluffHash')


def read_lua(path):
    return json.loads(path.read_text(encoding='utf-8').split('[===[', 1)[1].split(']===]', 1)[0])


def write_lua(path, value, generator):
    text = json.dumps(value, ensure_ascii=False, indent=2) + '\n'
    assert ']===]' not in text
    path.write_text(f'-- Generated by {generator}; identities and text provenance retained.\n'
                    "return require('json_data').decode([===[\n" + text + ']===])\n', encoding='utf-8')


def normalize(value):
    return re.sub(r'\s+', ' ', value.strip()).casefold()


def build(extracted, warinfo, community, effects):
    assert not extracted['conflicts'], 'Conflicting game translations must be investigated first'
    dictionaries = {lang: extracted['languages'][key] for lang, key in LANGUAGES.items()}
    records = [dict(p) for p in extracted['planets']]
    planets = {}
    by_hash = {}
    by_english = {}
    for p in records:
        planets.setdefault(p['debug'], []).append(p)
        by_hash.setdefault(p['settings_hash'], []).append(p)
        name = dictionaries['en'].get(str(p['name_hash']))
        if name:
            by_english.setdefault(normalize(name), []).append(p)
    api_planets = {}
    for p in warinfo['planetInfos']:
        index, settings = p['index'], p['settingsHash']
        candidates = by_hash.get(settings, [])
        source = 'settings_hash'
        # Two homeworld debug names no longer hash to their API identity. Only a
        # unique exact English text-ID match is accepted; debug suffix != index.
        if not candidates:
            english = community.get(str(index), {}).get('name', '')
            candidates = by_english.get(normalize(english), []) if english else []
            source = 'api_english_exact'
        ids = {v['name_hash'] for v in candidates}
        assert len(ids) == 1, f'Planet {index}: missing or ambiguous native text identity'
        native = sorted(candidates, key=lambda v: v['debug'])[0]
        item = {'index': index, 'settings_hash': settings, 'name_hash': native['name_hash'],
                'local_debug': native['debug'], 'source': source,
                'sector': community.get(str(index), {}).get('sector', '')}
        if source == 'api_english_exact':
            item['api_english'] = community[str(index)]['name']
        api_planets[str(index)] = item
        for candidate in candidates:
            assert 'index' not in candidate, 'One native record matched multiple API planets'
            candidate.update(index=index, sector=item['sector'])
    presence = {}
    required = {str(p['name_hash']) for p in records if p['name_hash']}
    for p in extracted['presence']:
        # Verified against 99 named native records in all three languages.
        # Historical aliases at +48/+52 are flags, not text references.
        item = {'debug': p['debug'], 'name_hash': p['text_refs'].get('32', 0),
                'description_hash': p['text_refs'].get('36', 0)}
        presence.setdefault(str(p['settings_hash']), []).append(item)
        required.update(str(item[k]) for k in ('name_hash', 'description_hash') if item[k])
    for entry in effects:
        required.update(str(entry['definition'][key]) for key in HASH_FIELDS if entry['definition'][key])
    strings = {lang: {key: texts[key] for key in sorted(required, key=int) if key in texts}
               for lang, texts in dictionaries.items()}
    return {'version': 1, 'language_ids': LANGUAGES,
            'required_ids': sorted(map(int, required)), 'strings': strings,
            'planets': planets, 'api_planets': api_planets, 'presence': presence,
            'presence_text_offsets': {'name': 32, 'description': 36},
            'game_sources': extracted.get('game_sources', {}),
            'coverage': {'local_records': len(records), 'api_planets': len(api_planets),
                         'planet_texts': {lang: sum(str(p['name_hash']) in d for p in records)
                                          for lang, d in dictionaries.items()}}}


def annotate_effects(entries, localization, pairs):
    by_id = {e['definition']['id']: e for e in entries}
    suffixes = {'en': 'en', 'zhs': 'zh', 'zht': 'zht'}
    for entry in entries:
        definition = entry['definition']
        entry['text_provenance'] = {}
        entry['unresolved_text_hashes'] = {}
        local = localization['presence'].get(str((definition.get('values') or [None])[0]), []) \
            if definition['effectType'] == 71 else []
        for lang, suffix in suffixes.items():
            texts = localization['strings'][lang]
            refs = entry['text_provenance'][lang] = {}
            missing = entry['unresolved_text_hashes'][lang] = {}
            for target, field in zip(('name', 'description', 'long_description', 'fluff_description'), HASH_FIELDS):
                key = str(definition[field])
                entry.pop(target + '_' + suffix, None)
                if key != '0' and texts.get(key):
                    entry[target + '_' + suffix] = texts[key]
                    refs[target] = {'source': 'api_hash', 'hash': int(key), 'field': field}
                elif key != '0':
                    missing[field] = int(key)
            if len(local) == 1:
                for target, field in (('name', 'name_hash'), ('description', 'description_hash')):
                    key = str(local[0][field])
                    if target not in refs and texts.get(key):
                        entry[target + '_' + suffix] = texts[key]
                        refs[target] = {'source': 'local_presence', 'hash': int(key),
                                        'debug': local[0]['debug'],
                                        'settings_hash': definition['values'][0],
                                        'offset': localization['presence_text_offsets'][target]}
    for effect, icon in pairs:
        actual, visual = by_id[effect], by_id[icon]
        assert actual['definition']['effectType'] == 40 and visual['definition']['effectType'] == 71
        for lang, suffix in suffixes.items():
            for field in ('name', 'description'):
                provenance = visual['text_provenance'][lang].get(field)
                if field not in actual['text_provenance'][lang] and provenance:
                    actual[field + '_' + suffix] = visual[field + '_' + suffix]
                    actual['text_provenance'][lang][field] = dict(provenance, source='paired_icon',
                                                                 paired_id=icon, origin=provenance['source'])
    # Description-only matches are deliberately marked as descriptive, not an
    # official title. At present no unmatched API title has a description match.
    for entry in entries:
        for lang, suffix in suffixes.items():
            refs = entry['text_provenance'][lang]
            if 'name' not in refs:
                field = next((f for f in ('description', 'long_description', 'fluff_description') if f in refs), None)
                if field:
                    entry['name_' + suffix] = entry[field + '_' + suffix]
                    refs['name'] = dict(refs[field], source='description', description_field=field)


def planet_names(localization):
    """Compatibility catalogue for consumers that do not have a record text ID."""
    result = {}
    for debug, records in localization['planets'].items():
        if len({p['name_hash'] for p in records}) != 1:
            continue  # Runtime resolves ambiguous debug names per record.
        p = records[0]
        key = str(p['name_hash'])
        names = {lang: localization['strings'][lang].get(key) for lang in LANGUAGES}
        if not names['en']:
            continue
        result[debug] = dict(index=p.get('index'), sector=p.get('sector', ''), name_hash=p['name_hash'],
                             en=names['en'], zhs=names['zhs'] or names['en'], zht=names['zht'] or names['en'])
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--extracted', type=Path, required=True)
    ap.add_argument('--warinfo', type=Path, required=True)
    ap.add_argument('--planets', type=Path, required=True, help='helldivers-2/json planets.json; identity join only')
    ap.add_argument('--effects', type=Path, default=ROOT / 'offline/galactic_effect_data.lua')
    ap.add_argument('--output', type=Path, default=ROOT / 'offline/localization_data.lua')
    ap.add_argument('--planet-catalog', type=Path, default=ROOT / 'offline/planet_data.lua')
    args = ap.parse_args()
    load = lambda p: json.loads(p.read_text(encoding='utf-8-sig'))
    catalog = read_lua(args.effects)
    data = build(load(args.extracted), load(args.warinfo), load(args.planets), catalog['effects'])
    data['source_sha256'] = {k: hashlib.sha256(p.read_bytes()).hexdigest()
                             for k, p in [('extracted', args.extracted), ('warinfo', args.warinfo), ('planets', args.planets)]}
    before = copy.deepcopy([e['definition'] for e in catalog['effects']])
    annotate_effects(catalog['effects'], data, catalog['pairs'])
    assert before == [e['definition'] for e in catalog['effects']], 'Localization changed a wire definition'
    write_lua(args.output, data, 'tools/update_game_localizations.py')
    write_lua(args.effects, catalog, 'tools/update_galactic_effects.py + tools/update_game_localizations.py')
    from planet_gen import luatable
    source = args.planet_catalog.read_text(encoding='utf-8')
    legacy = luatable.parse(source)
    legacy['planets'] = planet_names(data)
    args.planet_catalog.write_text(source.split('return ', 1)[0] + 'return ' + luatable.dump(legacy) + '\n', encoding='utf-8')
    print(json.dumps(data['coverage'], ensure_ascii=False))
    print('Effect titles:', {lang: sum('name' in e['text_provenance'][lang] for e in catalog['effects'])
                             for lang in LANGUAGES})


if __name__ == '__main__':
    main()
