# names RawData's entity-delta decoder gives the fields the game's deltas change: component -> offset -> path
def delta_names():
    D = os.path.join(RAWDATA, 'Data', 'entity_deltas')
    raw = json.load(open(os.path.join(D, 'entity_deltas_raw.json'), encoding='utf-8'))
    dec = json.load(open(os.path.join(D, 'entity_deltas_decoded.json'), encoding='utf-8'))
    R = {list(e)[0].upper(): list(e.values())[0] for e in raw['entities']}
    Dd = {h.upper(): e for it in dec['entities'] for h, e in it.items()}
    out = collections.defaultdict(dict)
    for h, e in R.items():
        d = Dd.get(h)
        if not d: continue
        for comp in e['modified_components']:
            tn = comp['type_name']; keys = [k for k in d if k.startswith(tn + '.')]
            words = []
            for dl in comp['deltas']:
                sz = dl['size']
                if sz in (1, 2): words.append(dl['offset'])
                else: words += [dl['offset'] + w for w in range(0, sz, 4)]
            if len(words) == len(keys):
                for off, k in zip(words, keys): out[tn][off] = k[len(tn) + 1:]
    return out
