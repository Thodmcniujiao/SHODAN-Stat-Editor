# Generates offline/modifier_data.lua: what the modifier pages need to name things.
#  - COMPONENTS: the entity-delta storage's component index -> component type (RawData's delta dump, 1.007.200)
#  - FIELDS: component type -> offset -> field path (+ 简体 / 繁體 labels), from RawData's delta decoder
#  - DELTAS / ENTITIES: display names of the deltas and entities (RawData), by hash
import os, re, json, collections
HERE = os.path.dirname(os.path.abspath(__file__))
exec(open(os.path.join(HERE, 'tl.py')).read())
exec(open(os.path.join(HERE, 'zh.py'), encoding='utf-8').read())
exec(open(os.path.join(HERE, 'mission_zh.py'), encoding='utf-8').read())
D = os.path.join(RAWDATA, 'Data', 'entity_deltas')
raw = json.load(open(os.path.join(D, 'entity_deltas_raw.json'), encoding='utf-8'))
dec = json.load(open(os.path.join(D, 'entity_deltas_decoded.json'), encoding='utf-8'))
R = {list(e)[0].upper(): list(e.values())[0] for e in raw['entities']}
Dd = {h.upper(): e for it in dec['entities'] for h, e in it.items()}
comps, fields, deltas = {}, collections.defaultdict(dict), {}
for h, e in R.items():
    d = Dd.get(h, {})
    if d.get('name') and d['name'] != 'N/A': deltas[h[2:]] = (d['name'], d.get('name_zh') or d['name'])
    for c in e['modified_components']:
        comps[c['component_index']] = (int(c['type_hash_hex'], 16), c['type_name'])
        keys = [k for k in d if k.startswith(c['type_name'] + '.')]
        offs = []
        for dl in c['deltas']:
            if dl["size"] in (1, 2): offs.append(dl["offset"])
            else: offs += [dl["offset"] + w for w in range(0, dl["size"], 4)]
        if len(offs) == len(keys):
            for off, k in zip(offs, keys): fields[c['type_name']][off] = k[len(c['type_name']) + 1:]
UNKSEG = re.compile(r'^(unk_[a-z0-9]+_(r)?0x[0-9A-Fa-f]{4}|0x[0-9A-F]{8})$')
def label(path):
    parts = []
    for seg in path.split('.'):
        m = re.match(r'^(.*?)(\[(\d+)\])?$', seg); base, idx = m.group(1), m.group(3)
        if UNKSEG.match(base):
            u = re.match(r'^unk_([a-z0-9]+?)_(r)?0x([0-9A-Fa-f]{4})$', base)
            if u:
                t = UNKT.get(u.group(1), (u.group(1), u.group(1))); o = int(u.group(3), 16)
                z = ('未知%s +0x%X' % (t[0], o), '未知%s +0x%X' % (t[1], o))
            else: z = ('未命名结构 ' + base, '未命名結構 ' + base)
        else: z = words(base)
        if idx is not None: z = (z[0] + ' %d' % (int(idx) + 1), z[1] + ' %d' % (int(idx) + 1))
        parts.append(z)
    return ' · '.join(p[0] for p in parts), ' · '.join(p[1] for p in parts)
names = {}
s = open(os.path.join(RAWDATA, 'Data', 'settings', 'EntityComponentMap.json'), encoding='utf-8').read()
for m in re.finditer(r'"hash_hex": "0x([0-9A-F]{16})",\s*"name": "([^"]*)",\s*"name_zh": "([^"]*)"', s):
    if m.group(2) != 'N/A': names[m.group(1)] = (m.group(2), m.group(3))
def ls(x): return "'" + x.replace('\\', '\\\\').replace("'", "\\'") + "'"
L = ['-- GENERATED by tools/component_gen/gen_modifiers.py: do not edit by hand.',
     "-- Names for the modifier pages: the entity-delta storage's component indexes and the fields its deltas change",
     "-- (Darctor/Helldivers2_RawData's delta dump, https://github.com/Darctor/Helldivers2_RawData, game 1.007.200), the deltas' and entities' display names.",
     'local M={COMPONENTS={},FIELDS={},DELTAS={},ENTITIES={}}']
for i, (h, n) in sorted(comps.items()): L.append('M.COMPONENTS[%d]={hash=0x%08X,name=%s}' % (i, h, ls(n)))
for tn in sorted(fields):
    L.append('M.FIELDS[%s]={' % ls(tn))
    for off, p in sorted(fields[tn].items()):
        a, b = label(p); L.append(' [%d]={%s,%s,%s},' % (off, ls(p), ls(a), ls(b)))
    L.append('}')
for h, (en, zh) in sorted(deltas.items()): L.append('M.DELTAS[%s]={%s,%s}' % (ls(h), ls(en), ls(zh)))
for h, (en, zh) in sorted(names.items()): L.append('M.ENTITIES[%s]={%s,%s}' % (ls(h), ls(en), ls(zh)))
L.append('return M')
out = os.environ.get('OUT_MODIFIER', os.path.join(HERE, '..', '..', 'offline', 'modifier_data.lua'))
open(out, 'w', encoding='utf-8', newline='').write('\n'.join(L) + '\n')
print('components', len(comps), 'field types', len(fields), 'deltas named', len(deltas), 'entities', len(names))
