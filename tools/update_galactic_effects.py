"""Build the effect-ID catalogue from a public GET, or an explicit saved response.

Names are annotations, never evidence of payload semantics. Reference names are
accepted only when both effectType and nameHash still match the live definition.
"""
import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
from urllib.request import urlopen

URL = 'https://api.live.prod.thehelldiversgame.com/api/WarSeason/GalacticWarEffects'
ROOT = Path(__file__).resolve().parents[1]
FIELDS = ('id', 'gameplayEffectId32', 'effectType', 'flags', 'nameHash',
          'descriptionFluffHash', 'descriptionGamePlayLongHash',
          'descriptionGamePlayShortHash', 'valueTypes', 'values')
# Explicitly researched pairs, not arithmetic neighbours. Runtime checks both
# types before classifying either member. A type-71 record alone is not an icon.
PAIRS = [(1202, 1203), (1243, 1245), (1244, 1386), (1248, 1249),
         (1303, 1310), (1306, 1309), (1307, 1308), (1360, 1361),
         (1377, 1378), (1380, 1379), (1401, 1400), (1402, 1403), (1413, 1414)]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--input', type=Path)
    ap.add_argument('--reference', type=Path, help='127MU assets/war_catalog.json')
    ap.add_argument('--english', type=Path, help='HelldiversData English.json')
    ap.add_argument('--output', type=Path, default=ROOT / 'offline/galactic_effect_data.lua')
    args = ap.parse_args()
    if args.input:
        raw = args.input.read_bytes()
    else:
        with urlopen(URL, timeout=30) as response:
            raw = response.read(4 * 1024 * 1024 + 1)
    assert len(raw) <= 4 * 1024 * 1024
    data = json.loads(raw)
    data = data.get('galacticEffects') if isinstance(data, dict) else data
    assert isinstance(data, list) and data
    reference = json.loads(args.reference.read_text(encoding='utf-8')) if args.reference else {}
    english = json.loads(args.english.read_text(encoding='utf-8-sig')) if args.english else {}
    strings = reference.get('strings', {})
    entries, seen = [], set()
    for row in sorted(data, key=lambda row: row['id']):
        assert type(row['id']) is int and row['id'] > 0 and row['id'] not in seen
        seen.add(row['id'])
        entry = {'definition': {key: row[key] for key in FIELDS}}
        ref = reference.get('effect_reference', {}).get(str(row['id']), {})
        if ref.get('effectType') == row['effectType'] and ref.get('nameHash') == row['nameHash']:
            entry['reference_name'] = ref.get('name', '')
            entry['reference_note'] = ref.get('note', '')
        for target, source in [('name', 'nameHash'), ('description', 'descriptionGamePlayShortHash'),
                               ('long_description', 'descriptionGamePlayLongHash')]:
            key = str(row[source])
            if isinstance(strings.get(key), str):
                entry[target + '_zh'] = strings[key]
            if isinstance(english.get(key), str):
                entry[target + '_en'] = english[key]
        entries.append(entry)
    result = {'source': URL, 'fetched_utc': datetime.now(timezone.utc).isoformat(timespec='seconds'),
              'source_sha256': hashlib.sha256(raw).hexdigest(),
              'reference_source': '127MU/SHODAN-Stat-Editor, 26aed0ef664d9b21718b36f15210be0615f89165/assets/war_catalog.json',
              'pairs': PAIRS, 'effects': entries}
    text = json.dumps(result, ensure_ascii=False, indent=2) + '\n'
    assert ']===]' not in text
    args.output.write_text('-- Generated by tools/update_galactic_effects.py; numeric ID order.\n'
                           "return require('json_data').decode([===[\n" + text + ']===])\n', encoding='utf-8')
    print(f'{len(entries)} definitions; {sum(1000 <= e["definition"]["id"] < 10000 for e in entries)} four-digit IDs')


if __name__ == '__main__':
    main()
